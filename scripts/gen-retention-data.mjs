#!/usr/bin/env node
// Writes packages/nutrition/src/retention-data.ts from data/catalog/retention-factors.json
// (USDA Table of Nutrient Retention Factors, Release 6), keeping the nutrients the app tracks.
// Run after scripts/usda/import_retention.py; a unit test fails if the two drift apart.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const snap = JSON.parse(readFileSync(path.join(root, "data/catalog/retention-factors.json"), "utf8"));
// App nutrient key -> USDA nutrient number used for its retention (see ADR-014).
const NUTRIENTS = { calcium: 301, iron: 303, magnesium: 304, potassium: 306, sodium: 307, zinc: 309, vitamin_c: 401, vitamin_b12: 418, folate_dfe: 417, vitamin_a_rae: 392 };
const lines = snap.factors.map((f) => {
  const r = Object.entries(NUTRIENTS)
    .filter(([, no]) => f.retention[String(no)] !== undefined)
    .map(([key, no]) => `${key}: ${f.retention[String(no)]}`)
    .join(", ");
  return `  ${f.code}: { d: ${JSON.stringify(f.description)}, r: { ${r} } },`;
});
const out = `// Generated by scripts/gen-retention-data.mjs from data/catalog/retention-factors.json. Do not edit.
// Source: ${snap.source.citation} ${snap.source.url} (content ${snap.contentSha256.slice(0, 12)})
// Percent of each nutrient left after cooking, by USDA cooking code.

export const RETENTION_SOURCE = ${JSON.stringify({ name: snap.source.name, url: snap.source.url, contentSha256: snap.contentSha256 })} as const;

export const RETENTION_NUTRIENT_NUMBERS: Record<string, number> = ${JSON.stringify(NUTRIENTS)};

export const RETENTION_FACTORS: Record<number, { d: string; r: Record<string, number> }> = {
${lines.join("\n")}
};
`;
writeFileSync(path.join(root, "packages/nutrition/src/retention-data.ts"), out);
console.log(`wrote ${snap.factors.length} codes`);
