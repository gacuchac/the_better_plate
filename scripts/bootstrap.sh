#!/usr/bin/env bash
# One-time-or-every-time setup. Idempotent: install deps, write a throwaway local .env,
# start PostgreSQL, migrate and seed. No manual configuration needed.
source "$(dirname "$0")/lib.sh"

# --- toolchain ---------------------------------------------------------------
command -v node >/dev/null || die "Node.js 22+ is required (https://nodejs.org)."
NODE_MAJOR=$(node -p 'process.versions.node.split(".")[0]')
[[ "$NODE_MAJOR" -ge 22 ]] || die "Node.js 22+ is required; found $(node -v)."
if ! command -v pnpm >/dev/null; then
  say "installing pnpm via corepack"
  corepack enable pnpm 2>/dev/null || npm install -g pnpm@10.28.0
fi

# --- dependencies (skip when the lockfile has not changed) --------------------
STAMP="node_modules/.bp-install-stamp"
LOCK_HASH=$( (cat pnpm-lock.yaml package.json apps/*/package.json packages/*/package.json) | sha256sum | cut -c1-16)
if [[ ! -f "$STAMP" || "$(cat "$STAMP")" != "$LOCK_HASH" ]]; then
  say "installing dependencies"
  pnpm install --frozen-lockfile
  echo "$LOCK_HASH" > "$STAMP"
fi

# --- local .env with generated throwaway secrets (git-ignored) ----------------
if [[ ! -f .env ]]; then
  say "writing local .env with a generated session secret"
  SECRET=$(node -e 'console.log(require("crypto").randomBytes(32).toString("hex"))')
  cat > .env <<ENV
# Generated by scripts/bootstrap.sh for LOCAL development only. Git-ignored. Safe to delete.
APP_ENV=local
PUBLIC_APP_URL=http://localhost:3000
PUBLIC_API_URL=http://localhost:4000
API_CORS_ALLOWED_ORIGINS=http://localhost:3000
DATABASE_URL=postgresql://betterplate:betterplate@localhost:5432/betterplate
SESSION_SECRET=$SECRET
# AI companion on locally; provider keys are encrypted with a key derived from SESSION_SECRET.
FEATURE_AI_COMPANION_ENABLED=true
# Claude/ChatGPT connector (MCP with OAuth) on locally (ADR-007).
FEATURE_MCP_CONNECTOR_ENABLED=true
# USDA key: read from the USDA_API_KEY (or USDA_FDC_API_KEY) environment variable; DEMO_KEY otherwise.
ENV
fi

# --- database ----------------------------------------------------------------
bash scripts/db-up.sh
say "migrating and loading the USDA starter catalog"
pnpm --silent --filter @betterplate/api db:setup

# --- informational checks ----------------------------------------------------
if [[ -n "${USDA_API_KEY:-}${USDA_FDC_API_KEY:-}" ]]; then KEY_STATE="USDA key set"; else KEY_STATE="no USDA key (DEMO_KEY fallback)"; fi
if curl -s -o /dev/null --max-time 5 "https://api.nal.usda.gov/fdc/v1/foods/search?query=apple&pageSize=1&api_key=DEMO_KEY" -w '%{http_code}' 2>/dev/null | grep -q '^[24]'; then
  NET_STATE="USDA API reachable"
else
  NET_STATE="USDA API not reachable from here (the committed catalog snapshot is used; refresh it with the GitHub Actions import job)"
fi
say "ready · $KEY_STATE · $NET_STATE"
